// Generates src/core/chain-data.ts: every EVM mainnet viem ships, as plain data.
//
// Importing `viem/chains` wholesale pulls ~1 MB into a browser bundle, mostly per-chain
// formatters and serializers. The kit only needs each chain's identity, RPCs, explorer and
// Multicall3 to connect, switch and read balances, so those fields are snapshotted here. Chains
// where Coven sends transactions (Arc and the CCTP chains) use their full viem definitions.
import { writeFileSync } from 'node:fs'
import * as chains from 'viem/chains'

const DEV_CHAIN_IDS = new Set([1337, 31337])
const seen = new Set()
const out = []
for (const chain of Object.values(chains)) {
  if (!chain || typeof chain !== 'object' || typeof chain.id !== 'number' || !chain.rpcUrls) continue
  if (chain.testnet || DEV_CHAIN_IDS.has(chain.id) || seen.has(chain.id)) continue
  seen.add(chain.id)
  const http = chain.rpcUrls.default?.http?.slice(0, 2) ?? []
  if (http.length === 0) continue
  const entry = {
    id: chain.id,
    name: chain.name,
    nativeCurrency: chain.nativeCurrency,
    rpcUrls: { default: { http } },
  }
  if (chain.blockExplorers?.default) entry.blockExplorers = { default: { name: chain.blockExplorers.default.name, url: chain.blockExplorers.default.url } }
  const multicall3 = chain.contracts?.multicall3
  if (multicall3?.address) entry.contracts = { multicall3: { address: multicall3.address, ...(multicall3.blockCreated ? { blockCreated: multicall3.blockCreated } : {}) } }
  out.push(entry)
}
out.sort((a, b) => a.name.localeCompare(b.name))

const header = `// Generated by scripts/gen-chains.mjs from viem ${(await import('viem/package.json', { with: { type: 'json' } })).default.version}. Do not edit.\n`
writeFileSync(
  'src/core/chain-data.ts',
  `${header}import type { Chain } from 'viem'\n\nexport const CHAIN_DATA: readonly Chain[] = ${JSON.stringify(out)}\n`,
)
console.log(`chain data: ${out.length} mainnets`)
